import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')

function parseData(html) {
  const match = html.match(/const DATA = ([\s\S]*?\n      \};)/)
  if (!match) throw new Error('Could not find DATA object in banner HTML')

  return vm.runInNewContext(`(${match[1].replace(/;$/, '')})`, {}, { timeout: 1000 })
}

function parseOfficialStores(source) {
  const match = source.match(/export const officialStoreDetails = (\[[\s\S]*?\]) as const/)
  if (!match) throw new Error('Could not find officialStoreDetails array')

  return vm.runInNewContext(match[1], {}, { timeout: 1000 })
}

function normalizeName(value) {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/&/g, 'and')
    .replace(/['’]/g, '')
    .replace(/\bb\.?v\.?\b/g, '')
    .replace(/\bgiant\s+store\b/g, 'giant store')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}

function firstByRole(banners, role) {
  return banners
    .filter((banner) => banner.role === role && banner.bg)
    .sort((a, b) => (a.slot ?? 99) - (b.slot ?? 99))[0]
}

function bannerTitle(entry, storeName) {
  const title = entry.title?.trim()
  if (title) return title

  return `Visit ${storeName}`
}

function bannerBody(entry) {
  if (entry.cta_url?.includes('5sterrenspecialist')) {
    return 'See why local riders recommend this Giant Store.'
  }

  return 'Explore the latest updates, services and offers from this store.'
}

export function buildStoreContentFromBannerHtml(html, officialStores) {
  const data = parseData(html)
  const officialStoresByName = new Map(
    officialStores.map((store) => [normalizeName(store.name), store]),
  )
  const entriesBySlug = new Map()

  for (const entry of data.banners ?? []) {
    if (entry.country !== 'The Netherlands') continue
    const store = officialStoresByName.get(normalizeName(entry.store))
    if (!store) continue

    const entries = entriesBySlug.get(store.slug) ?? []
    entries.push(entry)
    entriesBySlug.set(store.slug, entries)
  }

  const content = {}
  for (const [slug, entries] of entriesBySlug) {
    const store = officialStores.find((item) => item.slug === slug)
    const hero = firstByRole(entries, 'hero')
    const promo = firstByRole(entries, 'promo')
    const item = {}

    if (hero) {
      item.hero = { image: hero.bg }
    }

    if (promo && store) {
      item.banner = {
        title: bannerTitle(promo, store.name),
        body: bannerBody(promo),
        cta: promo.cta_text?.trim() || 'Discover',
        image: promo.bg,
      }
    }

    content[slug] = item
  }

  return content
}

function toGeneratedTypeScript(content) {
  return `// Generated by scripts/store-banner-content.mjs from src/scraped/giant_hero_banners.html.
// Do not edit by hand; put curated fixes in store-content-overrides.ts.

import type { ScrapedStoreContentMap } from './store-content'

export const scrapedStoreContent = ${JSON.stringify(content, null, 2)} as const satisfies ScrapedStoreContentMap
`
}

export function generateStoreContent({ htmlPath, officialStoresPath, outputPath }) {
  const html = readFileSync(htmlPath, 'utf8')
  const officialStoresSource = readFileSync(officialStoresPath, 'utf8')
  const officialStores = parseOfficialStores(officialStoresSource)
  const content = buildStoreContentFromBannerHtml(html, officialStores)

  writeFileSync(outputPath, toGeneratedTypeScript(content))
  return content
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const content = generateStoreContent({
    htmlPath: join(root, 'src/scraped/giant_hero_banners.html'),
    officialStoresPath: join(root, 'src/data/official-store-details.ts'),
    outputPath: join(root, 'src/data/store-content.generated.ts'),
  })

  console.log(`Generated scraped content for ${Object.keys(content).length} stores`)
}
