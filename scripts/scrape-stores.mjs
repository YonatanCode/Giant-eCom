import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT_PATH = fileURLToPath(new URL('../src/data/stores-nl.ts', import.meta.url))
const DEALERS_ENDPOINT = 'https://www.giant-bicycles.com/nl/stores/dealers'
const USER_AGENT = 'giant-store-connect/prototype (store-finder data build)'

const CAMPAIGN_TAGS = new Map([
  [2, 'Giant Store'],
  [3, 'Giant B2B Lease'],
  [4, 'Premium Retailer'],
  [5, 'DCF Supreme'],
  [7, 'DCF Premium'],
  [8, 'DCF Essential'],
  [9, 'E-bike Testcenter'],
  [12, 'E-bike certificaat'],
])

const SPOT_CHECK_STORES = ['Giant Store Bennebroek', 'Giant Store Amsterdam', 'Giant Store Marco']
const ADDRESS_RE = /^(.+?),\s*(\d{4}(?:\s*[A-Z]{2})?)\s+(.+?),\s*([A-Z]{2})$/i
const ADDRESS_WITHOUT_PROVINCE_RE = /^(.+?),\s*(\d{4}(?:\s*[A-Z]{2})?)\s+(.+)$/i
const MISSING_PROVINCES_BY_CITY = new Map([['Renesse', 'ZE']])

async function main() {
  const args = new Set(process.argv.slice(2))

  if (args.has('--check')) {
    const stores = await readGeneratedStores()
    validateStores(stores)
    return
  }

  const dealers = await fetchDealers()
  const stores = toStoreListings(dealers)

  await writeGeneratedStores(stores)
  console.log(`Wrote ${stores.length} stores to ${relativePath(OUT_PATH)}`)
}

async function fetchDealers() {
  const payload = {
    latitude: 52.132633,
    longitude: 5.291266,
    keyword: encodeURIComponent('Nederland'),
    NE_lat: 90,
    NE_lng: 180,
    SW_lat: -90,
    SW_lng: -180,
    campaigncodes: [],
    onlyGiantStores: false,
  }

  const response = await fetch(DEALERS_ENDPOINT, {
    method: 'POST',
    headers: {
      accept: 'application/json, text/plain, */*',
      'content-type': 'application/json;charset=UTF-8',
      referer: 'https://www.giant-bicycles.com/nl/stores',
      'user-agent': USER_AGENT,
    },
    body: JSON.stringify(payload),
  })

  if (!response.ok) {
    throw new Error(`Giant locator returned ${response.status} ${response.statusText}`)
  }

  const data = await response.json()
  assert(Array.isArray(data.dealers), 'Giant locator response did not include dealers[]')

  return data.dealers
}

function toStoreListings(dealers) {
  const seenSlugs = new Map()

  return dealers.map((dealer) => {
    const address = parseAddress(dealer)
    const tags = (dealer.CampaignCodes ?? []).map((code) => CAMPAIGN_TAGS.get(code)).filter(Boolean)
    const isGiantStore = Boolean(dealer.IsGiantStore) || tags.includes('Giant Store')
    const baseSlug = slugify(dealer.Name)
    const slugCount = seenSlugs.get(baseSlug) ?? 0
    const slug = slugCount === 0 ? baseSlug : `${baseSlug}-${slugCount + 1}`
    const website = normalizeWebsite(dealer.WebAddress)

    seenSlugs.set(baseSlug, slugCount + 1)

    return stripUndefined({
      slug,
      name: normalizeWhitespace(dealer.Name),
      isGiantStore,
      street: address.street,
      postcode: address.postcode,
      city: address.city,
      province: address.province,
      phone: normalizeWhitespace(dealer.Phone ?? ''),
      email: dealer.Email?.trim(),
      website,
      lat: Number(dealer.Latitude),
      lng: Number(dealer.Longitude),
      tags,
      detailHref: isGiantStore ? `/store/${slug}` : website ?? '#',
    })
  })
}

function parseAddress(dealer) {
  const value = normalizeWhitespace(dealer.AddressLocalized ?? '')
  const match = value.match(ADDRESS_RE)

  if (match) {
    return {
      street: normalizeStreet(match[1]),
      postcode: normalizeWhitespace(match[2]).toUpperCase(),
      city: normalizeWhitespace(match[3]),
      province: match[4].toUpperCase(),
    }
  }

  const fallbackMatch = value.match(ADDRESS_WITHOUT_PROVINCE_RE)

  if (!fallbackMatch) {
    throw new Error(`Could not parse dealer address: ${dealer.AddressLocalized}`)
  }

  const city = normalizeWhitespace(dealer.City ?? fallbackMatch[3])
  const province = dealer.State ?? MISSING_PROVINCES_BY_CITY.get(city)

  if (!province) {
    throw new Error(`Missing province for dealer address: ${dealer.AddressLocalized}`)
  }

  return {
    street: normalizeStreet(fallbackMatch[1]),
    postcode: normalizeWhitespace(fallbackMatch[2]).toUpperCase(),
    city,
    province: province.toUpperCase(),
  }
}

function normalizeStreet(value) {
  const street = normalizeWhitespace(value)
  const half = street.length / 2

  if (street.length % 2 === 0 && street.slice(0, half).trim() === street.slice(half).trim()) {
    return street.slice(0, half).trim()
  }

  return street
}

async function writeGeneratedStores(stores) {
  validateStores(stores)
  await mkdir(dirname(OUT_PATH), { recursive: true })
  await writeFile(
    OUT_PATH,
    `// Generated by scripts/scrape-stores.mjs - do not hand-edit. Source: ${DEALERS_ENDPOINT}.\n\n${storeListingInterface()}\n\nexport const nlStores: StoreListing[] = ${JSON.stringify(stores, null, 2)};\n`,
  )
}

async function readGeneratedStores() {
  const generated = await readFile(OUT_PATH, 'utf8')
  const match = generated.match(/export const nlStores: StoreListing\[] = (\[[\s\S]*\]);?\s*$/)

  if (!match) {
    throw new Error(`Could not find nlStores export in ${relativePath(OUT_PATH)}`)
  }

  return JSON.parse(match[1])
}

function validateStores(stores) {
  assert(Array.isArray(stores), 'nlStores must be an array')
  assert(
    stores.length >= 200 && stores.length <= 280,
    `expected roughly 240 store records, got ${stores.length}`,
  )

  const officialCount = stores.filter((store) => store.isGiantStore).length
  assert.equal(officialCount, 57, `expected exactly 57 official Giant Stores, got ${officialCount}`)

  const slugs = new Set()
  const outliers = []

  for (const store of stores) {
    for (const field of ['name', 'street', 'postcode', 'city', 'province', 'phone', 'slug']) {
      assert.equal(typeof store[field], 'string', `${store.slug || store.name} missing ${field}`)
      assert(store[field].trim().length > 0, `${store.slug || store.name} has empty ${field}`)
    }

    assert(!slugs.has(store.slug), `duplicate slug: ${store.slug}`)
    slugs.add(store.slug)
    assert.equal(typeof store.lat, 'number', `${store.slug} missing lat`)
    assert.equal(typeof store.lng, 'number', `${store.slug} missing lng`)
    assert(Number.isFinite(store.lat), `${store.slug} has invalid lat`)
    assert(Number.isFinite(store.lng), `${store.slug} has invalid lng`)

    if (store.lat < 50.7 || store.lat > 53.6 || store.lng < 3.3 || store.lng > 7.3) {
      outliers.push(`${store.name} (${store.lat}, ${store.lng})`)
    }
  }

  console.log(`Validated ${stores.length} stores (${officialCount} official Giant Stores)`)

  if (outliers.length > 0) {
    console.warn(`Coordinate outliers near NL bounds:\n${outliers.join('\n')}`)
  }

  for (const name of SPOT_CHECK_STORES) {
    const store = stores.find((candidate) => candidate.name === name)
    assert(store, `missing spot-check store: ${name}`)
    console.log(`${store.name}: ${store.street}, ${store.postcode} ${store.city}, ${store.province} (${store.lat}, ${store.lng})`)
  }
}

function storeListingInterface() {
  return `export interface StoreListing {
  slug: string
  name: string
  isGiantStore: boolean
  street: string
  postcode: string
  city: string
  province: string
  phone: string
  email?: string
  website?: string
  lat: number
  lng: number
  tags: string[]
  detailHref: string
}`
}

function slugify(value) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
}

function normalizeWebsite(value) {
  const trimmed = value?.trim()

  if (!trimmed) {
    return undefined
  }

  const withProtocol = /^https?:\/\//i.test(trimmed) ? trimmed : `https://${trimmed}`

  try {
    return new URL(withProtocol).toString().replace(/\/$/, '')
  } catch {
    return undefined
  }
}

function normalizeWhitespace(value) {
  return String(value).replace(/\s+/g, ' ').trim()
}

function stripUndefined(value) {
  return Object.fromEntries(Object.entries(value).filter(([, entryValue]) => entryValue !== undefined))
}

function relativePath(path) {
  return path.replace(`${process.cwd()}/`, '')
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
